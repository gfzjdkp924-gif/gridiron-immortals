/**
 * Gridiron Immortals — VERIFIED PLAYER POOL (pure data, no logic).
 * ---------------------------------------------------------------------------
 * SCHEMA
 *   Every record is one real NFL player, on one real franchise in one decade:
 *
 *   {
 *     name:     string           // Player's common name, e.g. "Emmitt Smith"
 *     position: Position         // One of the 10 roster positions (K included)
 *     team:     string           // Franchise name AS IT WAS IN THAT ERA
 *                                //   e.g. "Oakland Raiders", "Baltimore Colts"
 *     decade:   Decade           // "1960s" | ... | "2010s"
 *     rating:   number           // 0-100 all-time standing within the era.
 *                                //   ~95-99 immortal, ~88-94 franchise legend,
 *                                //   ~80-87 excellent starter, ~72-79 solid starter
 *     stats:    PlayerStats      // 2-3 key/value pairs for his average season
 *                                //   with THIS franchise in THIS decade (below)
 *   }
 *
 * THE `stats` FIELD — what the numbers mean
 *   An "average season" is the player's per-season average across the seasons he
 *   actually played for the tagged franchise inside the tagged decade. A season
 *   he split between two teams counts once, for the tagged team only. Seasons
 *   played for other franchises, and seasons outside the decade, are excluded.
 *   Counting stats are rounded to whole numbers; per-carry is one decimal; the
 *   kicker percentage is derived from the two whole numbers shown, so the line
 *   is internally consistent. Yards per carry is the average of the player's
 *   per-season yards-per-carry figures for the tagged franchise and decade —
 *   not total yards divided by total carries. It is a mean of per-season rates,
 *   so it cannot be recomputed from the other numbers on the card, and it is
 *   the method every RB record here uses — one method, not two.
 *
 *   Keys are short on purpose (they render on a phone card):
 *     pass  passing yards        rush  rushing yards        ypc   yards per carry
 *     td    touchdowns           rec   receptions           recy  receiving yards
 *     int   interceptions        sck   sacks                fr    fumble recoveries
 *     gp    games played         gs    games started        fg    "made-attempted"
 *     fgp   field-goal %
 *
 *   Per position:  QB pass/td/int · RB rush/td/ypc · WR & TE rec/recy/td ·
 *   OL gp/gs · DL sck/gp · LB sck/int · CB & S int/gp · K fg/fgp.
 *
 *   "n/a" means the NFL did not record that stat in that era — it is an honest
 *   gap, never a guess. Two consequences:
 *     · sacks are official only from 1982. DL/LB records from the 1960s and
 *       1970s therefore carry fumble recoveries and games instead of a sack
 *       count (sck: "n/a"); 1980s defenders' sack figure covers 1982-89 only.
 *     · games started was not an official stat before 1999, so OL records carry
 *       games played with gs: "n/a".
 *   Every number here traces to a source recorded in
 *   shared/research/pool-sources.md. Ratings are editorial judgement, not stats.
 *   Where no available source returns a record's primary stat the record is
 *   dropped rather than estimated; a leftover "n/a" marks a secondary stat the
 *   era never recorded (or, in four pass-1 cases, one no source would return).
 *
 * SCHEMA CONVENTIONS (follow these when extending the pool)
 *   1. DECADE BOUNDARY. A season belongs to the decade of its starting year:
 *      1989 is the 1980s, 1990 is the 1990s. Never split a season across two
 *      decades.
 *   2. POSITION TAGGING. Defensive linemen are the hand-in-the-dirt interior
 *      linemen and 4-3 ends; an edge rusher whose official designation is
 *      outside linebacker (DeMarcus Ware, Von Miller, Justin Houston, Joey
 *      Porter, Peter Boulware) is tagged LB even in a 3-4. Offensive line is
 *      one position (OL). A player who genuinely played two positions is tagged
 *      where he played most for that franchise in that decade.
 *   3. REPEATS AND RENAMES. A real player may appear in more than one group
 *      (Jerry Rice, Peyton Manning, Charles Haley, Paul Warfield, Terrell
 *      Owens, Kurt Warner, Edgerrin James, Jonathan Vilma, John Abraham, Jimmy
 *      Graham, Max Unger, Alan Faneca, Brett Favre, Matt Bryant, Aqib Talib);
 *      he keeps his plain name, and the engine then cannot draft him twice in
 *      one run. A franchise that changed its name between eras contributes one
 *      group per era-correct name (Oakland Raiders 1970s / Los Angeles Raiders
 *      1980s, St. Louis Rams 2000s / Los Angeles Rams 1970s) — two groups by
 *      design, never a renamed duplicate of the same group.
 *   4. HOMONYMS. The engine de-duplicates a run by NAME ALONE, so two different
 *      real players may never share a bare name in this array. When two
 *      different players genuinely share a name, append the franchise in
 *      parentheses to BOTH records: "Mark Clayton (Ravens)" and "Mark Clayton
 *      (Dolphins)" — with the 1980s Dolphins now in the pool, both carry the
 *      suffix. One real player appearing in two different groups (Jerry Rice,
 *      Peyton Manning, Charles Haley, Paul Warfield) keeps his plain name —
 *      that is the deliberate behaviour, and it stops the same man being
 *      drafted twice.
 *   5. TEAM SPELLING. Keep the era-correct franchise name exactly as already
 *      used ("Oakland Raiders", "Baltimore Colts", "Washington Redskins",
 *      "St. Louis Rams"): team + decade is the key a spin is grouped by, so a
 *      renamed variant would silently become a second, thinner group.
 *
 * HOW THE GAME USES IT
 *   A "spin" is one (team, decade) group. Players are looked up by that group,
 *   so this file is the only place player data lives — no player data in any
 *   component. The game auto-rerolls a spin with nothing left for the open
 *   slots, so thin groups are safe, and the server-side leaderboard validates
 *   every submitted pick against name + position + team + decade in THIS file.
 *
 * INTEGRATION (extending the pool)
 *   1. Keep the record shape above exactly.
 *   2. Reuse the existing `team` spelling for a franchise already listed here.
 *   3. A new decade tag must be added to the `Decade` union here AND given a
 *      strength factor in `ERA_STRENGTH` (src/lib/rating.ts), or the build
 *      fails — that record is keyed by decade, so a missing factor is a type
 *      error there. `POSITION_WEIGHT` (same file, src/lib/rating.ts) is where
 *      position weighting lives. Nothing in game.ts re-exports them.
 *   Nothing else needs touching: no player data is hard-coded in any component.
 *
 * SOURCES / ACCURACY NOTE
 *   Every record was re-checked against season-level stat tables and the stats
 *   above are the sourced per-season averages — see
 *   shared/research/pool-sources.md for the query and source of each. The
 *   remaining caveat is that ratings (0-100) are our own editorial call, and
 *   that anything we could not source is marked "n/a" rather than filled in.
 */

